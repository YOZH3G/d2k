/* d2k_p256.h — ECDH на кривой secp256r1 (P-256) для зонда подтверждения.
 *
 * ЗАЧЕМ. Зонд TLS 1.2 умел обмен ключами только на X25519. Поле 07.10.2026
 * (KN-1811): graph.facebook.com и api.facebook.com в TLS 1.2 выбирают
 * secp256r1, и зонд 253 раза за сутки отвечал «сервер выбрал группу 0x0017 —
 * зонд умеет только X25519». Ни один план этих целей так не подтверждался:
 * изъян зонда читался как неудача плана.
 *
 * ЧТО ЭТО И ЧЕГО НЕТ. Только ECDH: свой ключ, своя открытая точка и общий
 * секрет (координата x). Подписей ECDSA нет — зонд не проверяет подпись
 * ServerKeyExchange (см. d2k_tls12.h). Умножение не постоянного времени:
 * ключ одноразовый, сессия — зонд, секретов человека в ней нет; верность
 * важнее, и её держит тест по векторам независимой реализации (OpenSSL 3).
 *
 * Точки — несжатые, 65 байт: 0x04 || X || Y, как в TLS (RFC 8422 §5.4.1). */
#ifndef D2K_P256_H
#define D2K_P256_H
#include <stdint.h>

/* Новый случайный ключ: priv — скаляр 1..n-1 (big-endian), pub — точка. 0 или -1. */
int d2k_p256_keypair(uint8_t priv[32], uint8_t pub[65]);
/* Открытая точка своего ключа. 0 или -1 (скаляр вне 1..n-1). */
int d2k_p256_public(const uint8_t priv[32], uint8_t pub[65]);
/* Общий секрет: x(priv * peer). Точка собеседника проверяется: формат, поле,
 * принадлежность кривой; бесконечность в итоге — отказ. 0 или -1. */
int d2k_p256_ecdh(const uint8_t priv[32], const uint8_t peer[65], uint8_t out_x[32]);

#endif
