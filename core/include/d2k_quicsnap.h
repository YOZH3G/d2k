/* d2k_quicsnap.h — снимок QUIC-приветствия клиента из нескольких датаграмм.
 *
 * ЗАЧЕМ. Chrome с постквантовым key_share (ML-KEM) не вмещает ClientHello в
 * одну датаграмму и шлёт его двумя Initial (поле 15.10.2026). Снимок из одной
 * датаграммы — обрывок: мерить им нельзя, и цель уходила мериться встроенным
 * профилем холодного старта. Планы, подтверждённые на профиле, Chrome не
 * открывали: коробка вправе смотреть и на длину, и на раскладку (§6 ТЗ).
 *
 * ЧТО ХРАНИТ. Все Initial-датаграммы одного полёта как есть, байт в байт,
 * вместе с их размерами. Форма клиента — это и число датаграмм, и их длины, а
 * не только содержимое приветствия: собрать ClientHello и разложить его
 * заново по-своему значило бы снова мерить не тем.
 *
 * ФОРМАТ. 'Q','S','N', u8 count (1..D2K_QSNAP_MAX_DGRAMS), затем count раз:
 * u16 len (big endian) и len байт датаграммы. Первый байт 'Q' (0x51) не
 * бывает началом длинного заголовка QUIC — там обязателен бит 0x80 (RFC 9000
 * §17.2), — поэтому одиночная датаграмма прежнего формата отличима от пачки
 * без флага на проводе и без версии в самой пачке.
 *
 * Без выделений памяти: разбор отдаёт указатели внутрь буфера вызывающего.
 */
#ifndef D2K_QUICSNAP_H
#define D2K_QUICSNAP_H

#include <stddef.h>
#include <stdint.h>

/* Потолок снимка: две датаграммы Chrome по 1500 плюс заголовок пачки, с
   запасом под ECH GREASE и четвёртую датаграмму. Один и тот же в датапате, на
   проводе и в контроллере — иначе снимок обрезался бы на переходе. */
#define D2K_SHAPE_MAX 6144
/* Больше четырёх Initial клиент первым полётом не шлёт: четвёртая — уже
   запас. Предел нужен, чтобы пачка не росла от повторов по таймеру. */
#define D2K_QSNAP_MAX_DGRAMS 4

typedef struct {
    size_t n;
    const uint8_t *dg[D2K_QSNAP_MAX_DGRAMS];
    size_t len[D2K_QSNAP_MAX_DGRAMS];
} d2k_qsnap;

/* Форма приветствия клиента: по ней собственный клиент подтверждения строит
   своё приветствие такого же вида (число датаграмм, их размер, длина
   ClientHello). */
typedef struct {
    uint8_t  n;
    uint16_t dgram_len;
    uint16_t ch_len;
} d2k_quic_form;

/* 1 — p[0..n) начинается магией пачки. Разбор это НЕ обещает: проверка
   дешёвая и нужна там, где надо лишь отличить пачку от одиночной датаграммы. */
int d2k_qsnap_is(const uint8_t *p, size_t n);

/* Разбирает пачку без копирования: указатели смотрят внутрь p, и он обязан
   пережить out. 0 — успех. Усечение, лишний хвост, count вне 1..MAX,
   датаграмма длиннее 1500 — -1. */
int d2k_qsnap_parse(const uint8_t *p, size_t n, d2k_qsnap *out);

/* Упаковывает n датаграмм. Возвращает длину пачки, 0 — отказ. */
size_t d2k_qsnap_pack(const uint8_t *const *dg, const size_t *len, size_t n,
                      uint8_t *out, size_t cap);

/* Открытый ClientHello целиком: все датаграммы обязаны быть Initial ОДНОГО
   DCID и одной версии, а их кадры CRYPTO — сложиться без разрыва до
   заявленной длины сообщения. 0 — успех. Разные DCID (Retry, чужой поток),
   неизвестная версия, разрыв, обрывок — -1 и out не трогается. */
int d2k_qsnap_client_hello(const d2k_qsnap *s, uint8_t *out, size_t cap, size_t *out_len);

/* Имя (SNI) из собранного приветствия пачки. 0 — успех; -1, если приветствие
   не собралось или имени в нём нет (ECH, возобновление — не ошибка сети). */
int d2k_qsnap_sni(const d2k_qsnap *s, char *out, size_t cap);

/* Та же пачка с ОДНИМ новым DCID на все пакеты. Содержимое, номера пакетов,
   их длины, фиксированный бит и размеры датаграмм — из входа.
   Зачем: три параллельные попытки замера не могут идти одним DCID — сервер
   принимает их за повтор одного соединения и отвечает один раз (замер
   13.09.2026), и единогласие 3/3 становится недостижимым. 0 — успех. */
int d2k_qsnap_recid(const d2k_qsnap *s, uint8_t *out, size_t cap, size_t *out_len);

/* Форма пачки. 0 — успех, -1 — приветствие не собралось. */
int d2k_qsnap_form(const d2k_qsnap *s, d2k_quic_form *f);

#endif
