/* d2k_volprops.h — опрос свойств коробки по ОБРЫВУ ОБЪЁМА.
 *
 * Те же пять вопросов, что у d2k_props_ask, и тот же порядок; отличается
 * только то, чем засчитывается ответ. У d2k_props_ask это обмен с ServerHello
 * — верно для блока рукопожатия. При обрыве объёма рукопожатие проходит само,
 * и тем критерием первый же вопрос «прошёл» бы, ничего не померив. Здесь
 * вопрос засчитан, только если под его планом исходящая лестница больше не
 * рвётся: судит тот самый сигнал, которым блокировка и была измерена.
 *
 * Подробности и полевое основание — в шапке core/volprops.c. */
#ifndef D2K_VOLPROPS_H
#define D2K_VOLPROPS_H

#include <stddef.h>
#include <stdint.h>

#include "d2k_compose.h"
#include "d2k_meas.h"   /* d2k_hello */

/* Чем кончился один вопрос. Нужен трассе и журналу: «не прошло» бывает по
 * разным причинам, и слитые в одно они уводят поиск (тот же довод, что у
 * d2k_props_step). */
typedef enum {
    D2K_VP_NOT_ASKED = 0,  /* вопрос сегодня не собрать (нет байт, нет места) */
    D2K_VP_NO_PORT,        /* местный порт не занялся — наша неудача */
    D2K_VP_REFUSED,        /* датапат не взял план — тоже про нас */
    D2K_VP_UNREACHABLE,    /* лестница не дошла до цели: про линию, не про коробку */
    D2K_VP_STILL_CUT,      /* план встал, лестница всё равно оборвалась */
    D2K_VP_PASSED          /* обрыв исчез — свойство записано */
} d2k_vp_rc;

typedef struct {
    d2k_vp_rc rc;
    int       at_kb;        /* где оборвалась лестница под планом вопроса */
    char      reason[160];
} d2k_volprops_step;

/* Вход опроса. path — путь ресурса для лестницы (NULL или пусто — «/»), как
 * у d2k_volume_probe_path. hello_wire/tls12/plain — та же форма зонда, что у
 * базового объёмного замера: вопрос обязан мерить ту же лестницу, иначе
 * сравнивать «рвётся / не рвётся» не с чем. */
typedef struct {
    int         link_fd;
    const char *ip;
    uint16_t    port;
    d2k_hello   trigger;   /* снятое приветствие цели: из него имя для SET_NAME */
    d2k_hello   control;   /* снятое приветствие другого имени — тело фальшивок */
    int         plain;     /* открытый HTTP, без рукопожатия */
    int         tls12;
    size_t      hello_wire;
    const char *path;
} d2k_volprops_in;

/* Задаёт вопросы на живой цели через датапат. Возвращает вектор свойств:
 * записано только то, что ПРОШЛО (§2.4 — промах не пишет ничего, «не
 * измерено» не равно «нет»). steps может быть NULL.
 *
 * Прошедший вопрос оставляет свой план стоять (он и есть стратегия), не
 * прошедший снимается сразу. Опрос идёт до первого прохода. */
d2k_props d2k_props_ask_volume(const d2k_volprops_in *in, d2k_volprops_step *steps);

#endif /* D2K_VOLPROPS_H */
