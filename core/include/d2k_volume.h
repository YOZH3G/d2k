/* d2k_volume.h — направленные пробы блокировки по объёму соединения.
 *
 * ИЗМЕРЯЮТСЯ ДВА НЕСЛИВАЕМЫХ НАПРАВЛЕНИЯ. TX-лестница накачивает запросы
 * клиента (унаследованный probe), RX-проба читает HTTP-тело ответа. Для RX
 * обрыв считается особым классом только если два identity-ответа с одинаковым
 * Content-Length/chunked framing обрываются на близком объёме, а контроль,
 * действительно полученный в gzip, завершается.
 * Приметы tx-volume и rx-volume хранятся отдельно; действие из одной пробы не
 * объявляется лечением другой, пока кандидат не подтвердит собственный зонд.
 *
 * ПОЧЕМУ ПРОБА, А НЕ НАБЛЮДЕНИЕ ЗА ЧУЖИМ ТРАФИКОМ. Наблюдение отвечает на
 * вопрос «этот хост сейчас режут?» и ошибается в обе стороны: горизонт
 * видимости датапата — первые пакеты соединения, и здоровая крупная загрузка
 * выглядит оттуда ровно как обрыв. Проба отвечает на другой вопрос — «есть ли
 * этот блок на ЭТОЙ линии к ЭТОЙ сети» — за секунды, на своей мишени, своим
 * объёмом и не трогая пользовательский трафик.
 *
 * ЗАЧЕМ ПРОБА ИДЁТ ПЕРВОЙ. Пока результат направленного измерения неизвестен,
 * обычная классификация может приписать обрыв TLS рукопожатию/имени, хотя
 * соединение обрывается в теле ответа. Измерение даёт отдельную улику, не
 * отключая общий перебор: сохранённые планы коробки идут первыми, за ними —
 * подходящий объёмному профилю кандидат, затем остальные планы.
 *
 * TX-лестница перенесена из internal/volume (Go), z2k, 31.08.2026,
 * runnin4ik/dpi-detector. RX-пара identity/gzip добавлена отдельно по
 * наблюдению RuTracker: незжатое тело стабильно обрывалось около 23,9 КБ,
 * gzip-ответ завершался. Само наблюдение цели не фиксируется в коде.
 */
#ifndef D2K_VOLUME_H
#define D2K_VOLUME_H

#include <stddef.h>
#include <stdint.h>
#include "d2k_verify.h"

/* Ступень лестницы объёма и число ступеней: накопленный объём растёт
 * 4, 8, 12 … 40 КБ и покрывает весь наблюдавшийся разброс обрыва. */
#define D2K_VOL_CHUNK  4000
#define D2K_VOL_STEPS  10

/* Ниже этого объёма обрыв нашим классом не считается. До двенадцати килобайт
 * соединения рвутся по десятку обычных причин, и вердикт был бы шумом, а не
 * измерением. */
#define D2K_VOL_MIN_KB 12

typedef enum {
    /* Мишень не ответила вовсе. Про линию не сказано ничего: это НЕ «блока
       нет». */
    D2K_VOL_UNREACHABLE = 0,
    /* Соединение умерло за порогом. Это наш класс. */
    D2K_VOL_CUT,
    /* Лестница пройдена целиком, соединение живо. */
    D2K_VOL_PASSED,
    /* Объём до порога не дорос: документ кончился раньше или обрыв случился
       слишком рано. Вердикта НЕТ, и выдавать это за «блока нет» нельзя. */
    D2K_VOL_SHORT
} d2k_vol_verdict;

typedef struct {
    d2k_vol_verdict verdict;
    int      at_kb;       /* накопленный объём, на котором всё кончилось */
    int      rx_cut;      /* пара identity/gzip доказала повторяемый обрыв тела ответа */
    int      rx_at_kb;    /* входящее тело оборвалось около этого объёма */
    int      rx_expected_kb; /* Content-Length, если известен */
    int      rx_compressed_complete; /* контроль gzip дошёл до конца */
    int      rtt_ms;      /* измеренный RTT до мишени */
    char     reason[160]; /* человеческая причина, заполняется всегда */
    char     rx_reason[200]; /* отдельный исход GET, даже если TX не дошёл до TLS */
} d2k_vol_result;

/* Гоняет TX-лестницу, затем для HTTPS — парное RX-измерение тела ответа.
 * ip:port, имя sni предъявляется в TLS (пустое — идём по адресу). plain != 0
 * — открытый HTTP, без рукопожатия; отдельным параметром, а не выводом из
 * номера порта. tls12 и hello_wire выбирают форму baseline-зонда клиента.
 *
 * mark — метка SO_MARK (0 — не метить). Здесь она НУЖНА, в отличие от зонда
 * свойств: проба меряет ЛИНИЮ, а не работу плана, и уже поставленный план
 * исказил бы её. */
d2k_vol_result d2k_volume_probe(const char *ip, uint16_t port, const char *sni,
                                int plain, int tls12, size_t hello_wire,
                                uint32_t mark);

/* Чистая проверка трёх уже полученных ответов: две повторные identity-обрезки
 * и полный gzip-контроль. Нужна также тестам, чтобы границы RX-диагноза были
 * проверяемы без сетевых прогонов. Возвращает 1 только при подтверждённой
 * асимметрии и заполняет RX-поля out, иначе 0. */
int d2k_volume_rx_evidence(const d2k_ver_result *identity_a,
                           const d2k_ver_result *identity_b,
                           const d2k_ver_result *gzip_control,
                           d2k_vol_result *out);

const char *d2k_vol_verdict_name(d2k_vol_verdict v);

#endif /* D2K_VOLUME_H */
