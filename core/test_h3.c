/* test_h3.c — HTTP/3 без сети: байты запроса и разбор кода ответа.
 *
 * Сеть здесь не нужна и была бы вредна: предмет проверки — КОДИРОВАНИЕ, а
 * оно либо совпадает с текстом RFC, либо нет. Живые серверы проверяются
 * отдельно (spike/quicping.c) и другим вопросом: сходимся ли мы с ними
 * вообще.
 */
#include <stdio.h>
#include <string.h>

#include "d2k_h3.h"

static int fails;
#define CHECK(cond, msg)                                                      \
    do { if (!(cond)) { printf("ПРОВАЛ: %s\n", (msg)); fails++; } } while (0)

int main(void) {
    uint8_t buf[512];

    /* Управляющий поток: тип потока, пустой SETTINGS. Без него сервер вправе
       не отвечать вовсе, и молчание записалось бы блокировкой. */
    size_t n = d2k_h3_control(buf, sizeof buf);
    CHECK(n == 3 && buf[0] == 0x00 && buf[1] == 0x04 && buf[2] == 0x00,
          "управляющий поток собран не по RFC 9114");

    /* Запрос: кадр HEADERS, префикс секции из двух нулей, три индексных поля
       статической таблицы (GET, https, /) и :authority литералом. */
    n = d2k_h3_request("example.com", "/", buf, sizeof buf);
    CHECK(n > 0, "запрос не собрался");
    CHECK(buf[0] == 0x01, "кадр не HEADERS");
    size_t hdr = 2;   /* тип и длина (длина здесь однобайтная) */
    CHECK(buf[hdr] == 0x00 && buf[hdr + 1] == 0x00, "префикс секции не нулевой");
    CHECK(buf[hdr + 2] == 0xd1, ":method GET закодирован не индексом 17");
    CHECK(buf[hdr + 3] == 0xd7, ":scheme https закодирован не индексом 23");
    CHECK(buf[hdr + 4] == 0xc1, ":path / закодирован не индексом 1");
    CHECK(buf[hdr + 5] == 0x50, ":authority закодирован не литералом со ссылкой на имя");
    CHECK(buf[hdr + 6] == 11, "длина имени не та");
    CHECK(memcmp(buf + hdr + 7, "example.com", 11) == 0, "имя в запросе не то");

    /* Путь, отличный от "/": поле :path одно — литерал. Индексное «:path /»
       рядом с ним давало ДВА :path, и сервер (Cloudflare, Google) честно
       отвечал 400 целиком — а правило этапа данных засчитывало полный 400 как
       прошедшее плечо (поле 04.10, задача 50, раунд 2). */
    n = d2k_h3_request("example.com", "/big.css", buf, sizeof buf);
    CHECK(n > 0, "запрос с путём не собрался");
    {
        int indexed_root = 0, literal_path = 0;
        for (size_t i = hdr + 2; i < n; i++) {
            if (buf[i] == 0xc1) indexed_root++;
            if (buf[i] == 0x51 && i + 1 < n && buf[i + 1] == 8 &&
                i + 2 + 8 <= n && memcmp(buf + i + 2, "/big.css", 8) == 0) literal_path++;
        }
        CHECK(buf[hdr + 2] == 0xd1 && buf[hdr + 3] == 0xd7,
              "запрос с путём потерял :method/:scheme");
        CHECK(indexed_root == 0, "запрос с путём несёт второй :path (индексный \"/\")");
        CHECK(literal_path == 1, "запрос с путём не несёт свой :path литералом");
    }

    /* Ответ индексным полем статической таблицы: 25 это :status 200. */
    {
        uint8_t rsp[] = { 0x01, 0x03, 0x00, 0x00, 0xd9 };
        int st = 0;
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 200,
              "статус 200 индексным полем не разобран");
    }
    /* И все прочие статусы таблицы. */
    {
        struct { uint8_t idx; int st; } c[] = {
            { 24, 103 }, { 25, 200 }, { 26, 304 }, { 27, 404 }, { 28, 503 },
            { 63, 100 }, { 64, 204 }, { 65, 206 }, { 66, 302 }, { 67, 400 },
            { 68, 403 }, { 69, 421 }, { 70, 425 }, { 71, 500 },
        };
        for (size_t i = 0; i < sizeof c / sizeof c[0]; i++) {
            uint8_t rsp[8];
            size_t o = 0;
            rsp[o++] = 0x01;
            size_t len_at = o++;
            rsp[o++] = 0x00; rsp[o++] = 0x00;
            if (c[i].idx < 63) {
                rsp[o++] = (uint8_t)(0xc0 | c[i].idx);
            } else {
                rsp[o++] = 0xff;                       /* префикс исчерпан */
                rsp[o++] = (uint8_t)(c[i].idx - 63);   /* продолжение */
            }
            rsp[len_at] = (uint8_t)(o - 2);
            int st = 0;
            CHECK(d2k_h3_status(rsp, o, &st) == 0 && st == c[i].st,
                  "статус из статической таблицы разобран неверно");
        }
    }
    /* Литерал со ссылкой на имя :status, значение Хаффманом: три цифры это
       пятнадцать бит по пять, добитые единицами. */
    {
        int st = 0;
        /* Ссылка на имя :status — номер 27 в статической таблице, а в четыре
           бита префикса он не влезает: 0x5f это «префикс исчерпан», следом
           продолжение 27-15=12. Значение Хаффманом (RFC 7541 прил. B):
           цифры 4,0,4 это 011010 00000 011010, добитые единицами до трёх
           байт — 0x68 0x0d 0x7f. */
        uint8_t rsp[] = { 0x01, 0x08, 0x00, 0x00, 0x5f, 0x0c, 0x83, 0x68, 0x0d, 0x7f };
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 404,
              "статус Хаффманом не разобран");
    }
    /* Значение без Хаффмана — тремя цифрами как есть. */
    {
        int st = 0;
        uint8_t rsp[] = { 0x01, 0x08, 0x00, 0x00, 0x5f, 0x0c, 0x03, '2', '0', '1' };
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 201,
              "статус текстом не разобран");
    }
    /* Неизвестный кадр пропускается по длине, а не валит разбор. */
    {
        int st = 0;
        uint8_t rsp[] = { 0x21, 0x02, 0xaa, 0xbb, 0x01, 0x03, 0x00, 0x00, 0xd9 };
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 200,
              "неизвестный кадр не пропущен по длине");
    }
    /* Оборванный кадр — это НЕ «ответа нет»: честный отказ разбора. */
    {
        int st = 0;
        uint8_t rsp[] = { 0x01, 0x10, 0x00, 0x00 };
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) != 0,
              "оборванный кадр разобран как полный");
    }

    /* :status литералом со ссылкой на имя (индекс 24 = :status 103 как имя),
       значение Хаффманом. 301 = 011001 00000 00001 → 16 бит, 2 байта;
       503 = 011011 00000 011001 → 17 бит + 7 бит EOS = 3 байта. */
    {
        struct { uint8_t v[3]; size_t n; int st; } c[] = {
            { { 0x64, 0x01 }, 2, 301 },          /* 0110010000000001 */
            { { 0x6c, 0x0c, 0xff }, 3, 503 },    /* 011011 00000 011001 1111111 */
            { { 0x10, 0x01 }, 2, 200 },          /* 00010 00000 00000 1 */
        };
        for (size_t i = 0; i < sizeof c / sizeof c[0]; i++) {
            uint8_t rsp[16]; size_t o = 0;
            rsp[o++] = 0x01; size_t len_at = o++;
            rsp[o++] = 0x00; rsp[o++] = 0x00;
            rsp[o++] = 0x5f; rsp[o++] = 24 - 15;         /* 01N1 + idx 24 (4-бит префикс) */
            rsp[o++] = (uint8_t)(0x80 | c[i].n);         /* H=1, длина */
            memcpy(rsp + o, c[i].v, c[i].n); o += c[i].n;
            rsp[len_at] = (uint8_t)(o - 2);
            int st = 0;
            CHECK(d2k_h3_status(rsp, o, &st) == 0 && st == c[i].st,
                  "статус Хаффманом (6-битные цифры) не разобран");
        }
    }
    /* Литерал с литеральным именем (001N H xxx) пропускается, дальше идёт
       индексное поле :status 200. Имя "x-a", значение "1". */
    {
        int st = 0;
        uint8_t rsp[] = { 0x01, 0x09, 0x00, 0x00, 0x23, 'x', '-', 'a', 0x01, '1', 0xd9 };
        rsp[1] = sizeof rsp - 2;
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 200,
              "литерал с литеральным именем не пропущен");
    }
    /* Post-base формы (0001xxxx, 0000Nxxx) не принимаются за литерал. */
    {
        int st = 0;
        uint8_t rsp[] = { 0x01, 0x00, 0x00, 0x00, 0x11, 0x02, 0x01, '1', 0xd9 };
        rsp[1] = sizeof rsp - 2;
        CHECK(d2k_h3_status(rsp, sizeof rsp, &st) == 0 && st == 200,
              "post-base поле не пропущено");
    }

    if (fails == 0) { printf("HTTP/3: все проверки прошли\n"); return 0; }
    printf("HTTP/3: %d провалов\n", fails);
    return 1;
}
